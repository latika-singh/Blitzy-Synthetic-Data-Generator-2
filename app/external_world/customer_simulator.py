"""
Customer Simulator — Order generation, payment simulation, and dispute handling.

This module implements the ``CustomerSimulator`` class responsible for simulating
customer interactions with the ERP system.  It is a leaf consumer in the
``app.external_world`` package, integrating with:

* **Statistical Models** — ``AmountDistribution`` for log-normal order amounts by
  customer tier (Small $500–$5 K, Medium $2 K–$50 K, Large $10 K–$500 K);
  ``OrderFrequencyModel`` for Poisson-based daily order counts with day-of-week
  effects; ``PaymentTimingModel`` for 5-segment mixture model payment dates;
  ``SelectionModel`` for 70/30 repeat/new product selection and revenue-weighted
  customer batch selection.
* **Behaviour Profiles** — ``BehaviorProfile`` drives per-customer payment
  segments, short-pay rates, dispute rates, and order patterns.
* **Event Bus** — publishes ``TransactionCreated`` (order generation) and
  ``DiscrepancyDetected`` (dispute creation) events for cross-subsystem
  coordination.

All public methods are async coroutines (no blocking I/O).  Reproducible seeding
is achieved via ``numpy.random.RandomState``.

Data Contracts:
    * ``CustomerSimulatorConfig``  — Pydantic V2 configuration model.
    * ``CustomerOrder``           — Order data with UUID default factory.
    * ``CustomerPayment``         — Payment data with short-pay tracking.
    * ``CustomerDispute``         — Dispute data with type and status fields.

References:
    - README.md lines 456–508, 526–528, 554–558, 583–585
    - AAP Section 0.5.1 Group 7 (CustomerSimulator specification)
    - AAP Section 0.7.1 (Pydantic V2 at subsystem boundaries, constructor injection)
    - AAP Section 0.7.3 (async, no blocking I/O)
    - AAP Section 0.7.6 (structlog JSON logging to stdout)
"""

