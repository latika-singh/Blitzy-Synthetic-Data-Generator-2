class CustomerSimulatorConfig(BaseModel):
    """Configuration for the ``CustomerSimulator``.

    All fields have sensible defaults so that ``CustomerSimulatorConfig()``
    produces a valid configuration out of the box.

    Attributes:
        default_payment_terms: Default payment terms string (e.g. ``"Net 30"``).
        dispute_resolution_days_min: Minimum days to resolve a dispute.
        dispute_resolution_days_max: Maximum days to resolve a dispute.
        short_pay_percentage_min: Minimum fraction deducted in a short-pay
            scenario (1 %).
        short_pay_percentage_max: Maximum fraction deducted in a short-pay
            scenario (10 %).
        order_line_items_min: Minimum number of line items per order.
        order_line_items_max: Maximum number of line items per order.
        dispute_types: Possible dispute type labels.
    """

    default_payment_terms: str = "Net 30"
    dispute_resolution_days_min: int = Field(default=5, ge=1)
    dispute_resolution_days_max: int = Field(default=30, ge=1)
    short_pay_percentage_min: float = Field(default=0.01, ge=0.0, le=1.0)
    short_pay_percentage_max: float = Field(default=0.10, ge=0.0, le=1.0)
    order_line_items_min: int = Field(default=1, ge=1)
    order_line_items_max: int = Field(default=20, ge=1)
    dispute_types: List[str] = Field(
        default_factory=lambda: ["pricing", "quality", "quantity", "service"]
    )


