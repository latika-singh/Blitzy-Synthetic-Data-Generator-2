    def _get_customer_tier(self, customer: Dict[str, Any]) -> str:
        """Extract the customer interaction tier from a customer dictionary.

        Looks for ``"tier"`` or ``"customer_tier"`` keys, normalises to lower
        case, and validates against the canonical set.  Falls back to
        ``"standard"`` if absent or invalid.

        Args:
            customer: Customer dictionary.

        Returns:
            One of ``"strategic"``, ``"standard"``, ``"transactional"``.
        """
        raw_tier: str = str(
            customer.get("tier", customer.get("customer_tier", "standard"))
        ).lower().strip()
        if raw_tier in _VALID_TIERS:
            return raw_tier
        return "standard"

    def _get_customer_profile(self, customer: Dict[str, Any]) -> str:
        """Extract the payment quality profile name from a customer dictionary.

        Checks for a nested ``"behavior_profile"`` object with a
        ``"profile_name"`` key, or a top-level ``"profile"`` /
        ``"profile_name"`` field.  Falls back to ``"average"`` when
        unavailable.

        Args:
            customer: Customer dictionary.

        Returns:
            One of ``"excellent"``, ``"good"``, ``"average"``, ``"poor"``,
            ``"problem"``.
        """
        # Try nested behavior profile
        bp = customer.get("behavior_profile")
        if isinstance(bp, BehaviorProfile):
            return bp.profile_name
        if isinstance(bp, dict):
            name = str(bp.get("profile_name", "average")).lower().strip()
            if name in _VALID_PROFILES:
                return name

        # Try top-level keys
        for key in ("profile_name", "profile", "payment_profile"):
            val = customer.get(key)
            if val is not None:
                name = str(val).lower().strip()
                if name in _VALID_PROFILES:
                    return name

        return "average"

    def _resolve_behavior_profile(
        self, customer: Dict[str, Any]
    ) -> BehaviorProfile:
        """Resolve a full ``BehaviorProfile`` for a customer.

        Checks for an injected ``BehaviorProfile`` instance first, then
        constructs one from dictionary data, and finally falls back to a
        predefined template keyed by profile name.

        Args:
            customer: Customer dictionary.

        Returns:
            A ``BehaviorProfile`` instance.
        """
        bp = customer.get("behavior_profile")
        if isinstance(bp, BehaviorProfile):
            return bp
        if isinstance(bp, dict):
            try:
                return BehaviorProfile(**bp)
            except Exception:
                pass

        profile_name = self._get_customer_profile(customer)
        template = CUSTOMER_PROFILE_TEMPLATES.get(profile_name)
        if template is not None:
            return template
        return CUSTOMER_PROFILE_TEMPLATES.get("average", BehaviorProfile())

    def _build_line_items(
        self,
        customer: Dict[str, Any],
        num_items: int,
        total_amount: float,
        available_products: Optional[List[Dict[str, Any]]] = None,
    ) -> List[Dict[str, Any]]:
        """Build a list of order line-item dictionaries.

        Distributes *total_amount* across *num_items* line items using a
        Dirichlet distribution for realistic variation.  Product selection
        uses the ``SelectionModel`` when available.

        Args:
            customer: Customer dictionary (for purchase history lookup).
            num_items: Number of line items to generate.
            total_amount: Total order amount to distribute.
            available_products: Optional product catalogue.

        Returns:
            List of line-item dictionaries.
        """
        if num_items <= 0:
            return []

        items: List[Dict[str, Any]] = []

        # Dirichlet distribution for realistic per-item amounts
        raw_weights = self.rng.dirichlet(np.ones(num_items))
        item_amounts = [round(float(w * total_amount), 2) for w in raw_weights]

        # Correct rounding residual on the last item
        rounding_diff = round(total_amount - sum(item_amounts), 2)
        item_amounts[-1] = round(item_amounts[-1] + rounding_diff, 2)

        purchase_history: Optional[List[Dict[str, Any]]] = customer.get(
            "purchase_history"
        )

        for idx in range(num_items):
            quantity: int = max(1, int(self.rng.randint(1, 100)))
            item: Dict[str, Any] = {
                "line_number": idx + 1,
                "quantity": quantity,
                "unit_price": round(item_amounts[idx] / max(1, quantity), 2),
                "amount": item_amounts[idx],
            }

            # Product selection via SelectionModel (70/30 repeat/new)
            if available_products and self._selection_model is not None:
                try:
                    product = self._selection_model.select_product(
                        available_products=available_products,
                        purchase_history=purchase_history,
                    )
                    item["product_id"] = product.get(
                        "product_id",
                        product.get("id", f"PROD-{idx + 1}"),
                    )
                    item["product_name"] = product.get(
                        "name",
                        product.get("product_name", f"Product {idx + 1}"),
                    )
                except Exception:
                    item["product_id"] = f"PROD-{idx + 1}"
                    item["product_name"] = f"Product {idx + 1}"
            elif available_products:
                # No selection model — pick randomly from catalogue
                prod_idx = int(self.rng.randint(0, len(available_products)))
                product = available_products[prod_idx]
                item["product_id"] = product.get(
                    "product_id",
                    product.get("id", f"PROD-{idx + 1}"),
                )
                item["product_name"] = product.get(
                    "name",
                    product.get("product_name", f"Product {idx + 1}"),
                )
            else:
                item["product_id"] = f"PROD-{idx + 1}"
                item["product_name"] = f"Product {idx + 1}"

            items.append(item)

        return items
