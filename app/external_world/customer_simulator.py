class CustomerSimulator:
    """Simulates customer interactions with the ERP system.

    This simulator generates realistic customer orders, payments, and disputes
    by composing statistical distribution models and behaviour profiles.

    Dependencies are injected via the constructor (AAP Section 0.7.1).  All
    public methods are async coroutines with no blocking I/O (AAP Section 0.7.3).

    Args:
        config: Simulator configuration.  Defaults are used when ``None``.
        amount_distribution: Injected ``AmountDistribution`` for order-amount
            sampling by customer tier (log-normal).
        order_frequency_model: Injected ``OrderFrequencyModel`` for Poisson
            daily order counts with day-of-week effects.
        payment_timing_model: Injected ``PaymentTimingModel`` for 5-segment
            mixture model payment dates.
        selection_model: Injected ``SelectionModel`` for 70/30 repeat/new
            product selection and revenue-weighted customer batch selection.
        event_bus: Injected ``EventBus`` for publishing ``TransactionCreated``
            and ``DiscrepancyDetected`` events.
        seed: Optional RNG seed for reproducible simulation runs.
    """

    # ------------------------------------------------------------------
    # Construction
    # ------------------------------------------------------------------

    def __init__(
        self,
        config: Optional[CustomerSimulatorConfig] = None,
        amount_distribution: Optional[AmountDistribution] = None,
        order_frequency_model: Optional[OrderFrequencyModel] = None,
        payment_timing_model: Optional[PaymentTimingModel] = None,
        selection_model: Optional[SelectionModel] = None,
        event_bus: Optional[EventBus] = None,
        seed: Optional[int] = None,
    ) -> None:
        self._config: CustomerSimulatorConfig = config or CustomerSimulatorConfig()
        self._amount_distribution = amount_distribution
        self._order_frequency_model = order_frequency_model
        self._payment_timing_model = payment_timing_model
        self._selection_model = selection_model
        self._event_bus = event_bus
        self.rng: np.random.RandomState = np.random.RandomState(seed)

        logger.info(
            "customer_simulator_initialized",
            seed=seed,
            default_payment_terms=self._config.default_payment_terms,
            dispute_types=self._config.dispute_types,
        )

    # ------------------------------------------------------------------
    # Order Generation
    # ------------------------------------------------------------------

    async def generate_customer_order(
        self,
        customer: Dict[str, Any],
        simulation_date: date,
        available_products: Optional[List[Dict[str, Any]]] = None,
    ) -> CustomerOrder:
        """Generate a single customer purchase order.

        Determines the customer tier and behaviour profile, samples an order
        amount from ``AmountDistribution`` by size tier, selects products via
        ``SelectionModel`` (70 % repeat / 30 % new), and publishes a
        ``TransactionCreated`` event through the ``EventBus``.

        Args:
            customer: Customer dictionary containing at minimum a
                ``"customer_id"`` key, plus optionally ``"tier"`` /
                ``"customer_tier"``, ``"behavior_profile"``,
                ``"purchase_history"``, and ``"payment_terms"``.
            simulation_date: Current simulation date for the order.
            available_products: Optional product catalogue for line-item
                selection.  Falls back to synthetic placeholders when absent.

        Returns:
            A fully populated ``CustomerOrder`` instance.
        """
        customer_id: str = str(
            customer.get("customer_id", customer.get("id", str(uuid4())))
        )
        tier: str = self._get_customer_tier(customer)
        size_tier: str = _TIER_TO_SIZE.get(tier, "medium")

        # --- Order amount ---------------------------------------------------
        if self._amount_distribution is not None:
            total_amount: float = float(
                self._amount_distribution.sample_customer_order_amount(tier=size_tier)
            )
        else:
            # Fallback: simple random amount within a reasonable range
            total_amount = float(round(self.rng.uniform(500.0, 50_000.0), 2))

        # --- Line items -----------------------------------------------------
        num_items: int = int(
            self.rng.randint(
                self._config.order_line_items_min,
                self._config.order_line_items_max + 1,
            )
        )

        items: List[Dict[str, Any]] = self._build_line_items(
            customer=customer,
            num_items=num_items,
            total_amount=total_amount,
            available_products=available_products,
        )

        # --- Payment terms --------------------------------------------------
        payment_terms: str = str(
            customer.get("payment_terms", self._config.default_payment_terms)
        )

        # --- Assemble order -------------------------------------------------
        order = CustomerOrder(
            customer_id=customer_id,
            order_date=simulation_date,
            items=items,
            total_amount=round(total_amount, 2),
            payment_terms=payment_terms,
            status="pending",
        )

        # --- Publish event --------------------------------------------------
        if self._event_bus is not None:
            event = TransactionCreated(
                payload={
                    "transaction_id": order.order_id,
                    "transaction_type": "customer_order",
                    "amount": order.total_amount,
                    "currency": order.currency,
                    "customer_id": customer_id,
                    "initiator_agent_id": "customer_simulator",
                },
            )
            try:
                await self._event_bus.publish(event)
            except Exception as exc:
                logger.warning(
                    "event_publish_failed",
                    event_type="TransactionCreated",
                    order_id=order.order_id,
                    error=str(exc),
                )

        logger.info(
            "customer_order_generated",
            customer_id=customer_id,
            amount=order.total_amount,
            item_count=num_items,
            tier=tier,
            order_id=order.order_id,
        )

        return order

    async def generate_daily_orders(
        self,
        customers: List[Dict[str, Any]],
        simulation_date: date,
        available_products: Optional[List[Dict[str, Any]]] = None,
    ) -> List[CustomerOrder]:
        """Generate all customer orders for a single simulation day.

        Uses ``OrderFrequencyModel.sample_order_count()`` to determine the
        total order count (Poisson with day-of-week effects), then selects
        which customers place orders via
        ``SelectionModel.select_customers_batch()`` (revenue-weighted).

        Args:
            customers: Pool of customer dictionaries.
            simulation_date: The business date being simulated.
            available_products: Optional product catalogue.

        Returns:
            List of ``CustomerOrder`` objects generated for the day.
        """
        if not customers:
            logger.info(
                "daily_orders_generated",
                date=simulation_date.isoformat(),
                order_count=0,
                reason="empty_customer_pool",
            )
            return []

        # --- Determine order count ------------------------------------------
        if self._order_frequency_model is not None:
            order_count: int = self._order_frequency_model.sample_order_count(
                simulation_date
            )
        else:
            # Fallback: small random count
            order_count = int(
                self.rng.randint(1, max(2, len(customers) // 5 + 1))
            )

        order_count = max(0, order_count)
        if order_count == 0:
            logger.info(
                "daily_orders_generated",
                date=simulation_date.isoformat(),
                order_count=0,
            )
            return []

        # --- Select customers -----------------------------------------------
        if self._selection_model is not None:
            selected_customers: List[Dict[str, Any]] = (
                self._selection_model.select_customers_batch(
                    customers, order_count
                )
            )
        else:
            # Fallback: uniform random selection with replacement
            indices = self.rng.choice(
                len(customers), size=order_count, replace=True
            )
            selected_customers = [customers[int(i)] for i in indices]

        # --- Generate orders ------------------------------------------------
        orders: List[CustomerOrder] = []
        for cust in selected_customers:
            order = await self.generate_customer_order(
                customer=cust,
                simulation_date=simulation_date,
                available_products=available_products,
            )
            orders.append(order)

        logger.info(
            "daily_orders_generated",
            date=simulation_date.isoformat(),
            order_count=len(orders),
        )
        return orders

    # ------------------------------------------------------------------
    # Payment Simulation
    # ------------------------------------------------------------------

    async def simulate_payment(
        self,
        customer: Dict[str, Any],
        invoice: Dict[str, Any],
        simulation_date: date,
    ) -> CustomerPayment:
        """Simulate a customer payment against an outstanding invoice.

        Uses the customer's ``BehaviorProfile`` to determine payment timing
        (via ``PaymentTimingModel``), short-pay probability, and amount.

        Args:
            customer: Customer dictionary with optional ``"behavior_profile"``
                and ``"payment_terms"`` keys.
            invoice: Invoice dictionary containing at minimum ``"invoice_id"``
                and ``"amount"`` (or ``"amount_due"``).
            simulation_date: Current simulation date.

        Returns:
            A ``CustomerPayment`` instance.
        """
        customer_id: str = str(
            customer.get("customer_id", customer.get("id", str(uuid4())))
        )
        invoice_id: str = str(
            invoice.get("invoice_id", invoice.get("id", str(uuid4())))
        )
        amount_due: float = float(
            invoice.get("amount", invoice.get("amount_due", 0.0))
        )

        # --- Behaviour profile ----------------------------------------------
        profile: BehaviorProfile = self._resolve_behavior_profile(customer)

        # --- Invoice date ---------------------------------------------------
        invoice_date_raw = invoice.get(
            "invoice_date", invoice.get("date", simulation_date)
        )
        if isinstance(invoice_date_raw, str):
            invoice_date: date = date.fromisoformat(invoice_date_raw)
        elif isinstance(invoice_date_raw, datetime):
            invoice_date = invoice_date_raw.date()
        elif isinstance(invoice_date_raw, date):
            invoice_date = invoice_date_raw
        else:
            invoice_date = simulation_date

        payment_terms: str = str(
            customer.get("payment_terms", self._config.default_payment_terms)
        )

        # --- Payment date via PaymentTimingModel ----------------------------
        if self._payment_timing_model is not None:
            payment_date: date = self._payment_timing_model.get_payment_date(
                invoice_date=invoice_date,
                payment_terms=payment_terms,
                customer_profile=profile.profile_name,
            )
        else:
            # Fallback: due in 30 days from invoice date
            payment_date = invoice_date + timedelta(days=30)

        # Ensure the payment date is not before the invoice date
        if payment_date < invoice_date:
            payment_date = invoice_date

        # --- Short-pay logic ------------------------------------------------
        is_short_pay: bool = False
        short_pay_reason: Optional[str] = None
        amount_paid: float = amount_due

        short_pay_rate = profile.payment_behavior.short_pay_rate
        if short_pay_rate > 0.0 and self.rng.random() < short_pay_rate:
            is_short_pay = True
            short_pay_pct: float = float(
                self.rng.uniform(
                    self._config.short_pay_percentage_min,
                    self._config.short_pay_percentage_max,
                )
            )
            amount_paid = round(amount_due * (1.0 - short_pay_pct), 2)
            short_pay_reason = (
                f"Short payment of {short_pay_pct:.1%} — customer deducted "
                f"${amount_due - amount_paid:.2f} from invoice {invoice_id}"
            )

        payment = CustomerPayment(
            customer_id=customer_id,
            invoice_id=invoice_id,
            payment_date=payment_date,
            amount_due=round(amount_due, 2),
            amount_paid=round(amount_paid, 2),
            is_short_pay=is_short_pay,
            short_pay_reason=short_pay_reason,
        )

        logger.info(
            "customer_payment_simulated",
            customer_id=customer_id,
            invoice_id=invoice_id,
            amount_paid=payment.amount_paid,
            amount_due=payment.amount_due,
            is_short_pay=is_short_pay,
        )
        return payment

    async def simulate_daily_payments(
        self,
        customers: List[Dict[str, Any]],
        outstanding_invoices: List[Dict[str, Any]],
        simulation_date: date,
    ) -> List[CustomerPayment]:
        """Simulate all customer payments due on a given simulation date.

        Filters *outstanding_invoices* to those whose expected payment date
        falls on or before *simulation_date*, then simulates each payment.

        Args:
            customers: Pool of customer dictionaries.
            outstanding_invoices: Invoices awaiting payment.
            simulation_date: The business date being simulated.

        Returns:
            List of ``CustomerPayment`` instances for payments due today.
        """
        if not outstanding_invoices:
            return []

        # Build customer lookup for efficient matching
        customer_map: Dict[str, Dict[str, Any]] = {}
        for cust in customers:
            cid = str(cust.get("customer_id", cust.get("id", "")))
            if cid:
                customer_map[cid] = cust

        payments: List[CustomerPayment] = []
        for inv in outstanding_invoices:
            # Determine the invoice's expected payment / due date
            due_date_raw = inv.get(
                "payment_due_date",
                inv.get("due_date", inv.get("expected_payment_date")),
            )
            if due_date_raw is None:
                # If no explicit due date, compute from invoice date + 30d
                inv_date_raw = inv.get("invoice_date", inv.get("date"))
                if isinstance(inv_date_raw, str):
                    inv_date = date.fromisoformat(inv_date_raw)
                elif isinstance(inv_date_raw, date):
                    inv_date = inv_date_raw
                else:
                    continue
                due_date = inv_date + timedelta(days=30)
            else:
                if isinstance(due_date_raw, str):
                    due_date = date.fromisoformat(due_date_raw)
                elif isinstance(due_date_raw, datetime):
                    due_date = due_date_raw.date()
                elif isinstance(due_date_raw, date):
                    due_date = due_date_raw
                else:
                    continue

            if due_date > simulation_date:
                continue

            cust_id = str(inv.get("customer_id", inv.get("id", "")))
            cust = customer_map.get(cust_id, {"customer_id": cust_id})

            payment = await self.simulate_payment(
                customer=cust,
                invoice=inv,
                simulation_date=simulation_date,
            )
            payments.append(payment)

        return payments

