    # Dispute Handling
    # ------------------------------------------------------------------

    async def simulate_dispute(
        self,
        customer: Dict[str, Any],
        invoice: Dict[str, Any],
        simulation_date: date,
    ) -> Optional[CustomerDispute]:
        """Probabilistically simulate a customer dispute for an invoice.

        Dispute probability is driven by the customer's ``BehaviorProfile``
        ``dispute_rate`` field.  When triggered, a ``DiscrepancyDetected``
        event is published via the ``EventBus``.

        Args:
            customer: Customer dictionary.
            invoice: Invoice dictionary (must contain ``"invoice_id"`` and
                ``"amount"`` or ``"amount_due"``).
            simulation_date: Current simulation date.

        Returns:
            A ``CustomerDispute`` instance if triggered, otherwise ``None``.
        """
        profile: BehaviorProfile = self._resolve_behavior_profile(customer)

        # Check whether a dispute occurs
        dispute_rate = profile.payment_behavior.dispute_rate
        if dispute_rate <= 0.0 or self.rng.random() >= dispute_rate:
            return None

        customer_id: str = str(
            customer.get("customer_id", customer.get("id", str(uuid4())))
        )
        invoice_id: str = str(
            invoice.get("invoice_id", invoice.get("id", str(uuid4())))
        )
        invoice_amount: float = float(
            invoice.get("amount", invoice.get("amount_due", 0.0))
        )

        # --- Dispute type ---------------------------------------------------
        dispute_type: str = str(self.rng.choice(self._config.dispute_types))

        # --- Dispute amount (partial or full) --------------------------------
        dispute_fraction: float = float(self.rng.uniform(0.1, 1.0))
        dispute_amount: float = round(invoice_amount * dispute_fraction, 2)

        # --- Estimated resolution date ---------------------------------------
        resolution_days: int = int(
            self.rng.randint(
                self._config.dispute_resolution_days_min,
                self._config.dispute_resolution_days_max + 1,
            )
        )
        resolution_date: date = simulation_date + timedelta(days=resolution_days)

        dispute = CustomerDispute(
            customer_id=customer_id,
            invoice_id=invoice_id,
            dispute_type=dispute_type,
            dispute_amount=dispute_amount,
            dispute_date=simulation_date,
            resolution_date=resolution_date,
            status="open",
        )

        # --- Publish event --------------------------------------------------
        if self._event_bus is not None:
            event = DiscrepancyDetected(
                payload={
                    "discrepancy_type": f"customer_dispute_{dispute_type}",
                    "transaction_id": invoice_id,
                    "severity": "medium",
                    "details": (
                        f"Customer {customer_id} disputes "
                        f"${dispute_amount:.2f} on invoice "
                        f"{invoice_id} ({dispute_type})"
                    ),
                    "detected_by_agent_id": "customer_simulator",
                    "dispute_id": dispute.dispute_id,
                },
            )
            try:
                await self._event_bus.publish(event)
            except Exception as exc:
                logger.warning(
                    "event_publish_failed",
                    event_type="DiscrepancyDetected",
                    dispute_id=dispute.dispute_id,
                    error=str(exc),
                )

        logger.warning(
            "customer_dispute_created",
            customer_id=customer_id,
            invoice_id=invoice_id,
            dispute_type=dispute_type,
            amount=dispute_amount,
            resolution_days=resolution_days,
            dispute_id=dispute.dispute_id,
        )
        return dispute

    async def check_disputes_for_invoices(
        self,
        customer: Dict[str, Any],
        invoices: List[Dict[str, Any]],
        simulation_date: date,
    ) -> List[CustomerDispute]:
        """Check for disputes across multiple invoices for a customer.

        Iterates over each invoice and calls :meth:`simulate_dispute`.  Only
        non-``None`` results are included in the returned list.

        Args:
            customer: Customer dictionary.
            invoices: List of invoice dictionaries.
            simulation_date: Current simulation date.

        Returns:
            List of ``CustomerDispute`` instances for triggered disputes.
        """
        disputes: List[CustomerDispute] = []
        for inv in invoices:
            dispute = await self.simulate_dispute(
                customer=customer,
                invoice=inv,
                simulation_date=simulation_date,
            )
            if dispute is not None:
                disputes.append(dispute)
        return disputes

